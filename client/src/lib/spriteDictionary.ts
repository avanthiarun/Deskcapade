const escapeRegExp = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const keywordPatterns = new Map<SpriteTemplate, RegExp>(
  SPRITE_DICTIONARY.map((t) => [
    t,
    new RegExp(`\\b(?:${t.keywords.map(escapeRegExp).join("|")})(?:e?s)?\\b`, "i"),
  ]),
);

/** The premade template for a detection label, or null when the dictionary has no match. */
export function findSpriteTemplate(label: string): SpriteTemplate | null {
  for (const t of SPRITE_DICTIONARY) {
    if (keywordPatterns.get(t)?.test(label)) return t;
  }
  return null;
}
