/* ------------------------------------------------------------------
   Premade pixel-art sprites for common desk objects.
   A detection label is matched against each entry's keywords, in order (first match wins),
   so put more specific entries (headphones) before general ones (phone).

   Each template is a small pixel grid. One character = one pixel:
     .  transparent
     o  outline (always #2b1d3a)
     b  body       ┐
     s  shade      ├ recolored from the real object's color in the photo
     h  highlight  ┘
     anything else = a fixed color from FIXED_COLORS (or the entry's own `colors`)

   To add an object: copy an entry, give it new keywords, draw its rows (all the same width).
   Keep shapes simple: a cup is a cup, a cube is a cube.
   ------------------------------------------------------------------ */

export const OUTLINE_COLOR = "#2b1d3a";

/** Colors for template characters that are not recolored from the photo. */
export const FIXED_COLORS: Readonly<Record<string, string>> = {
  w: "#fff7e6", // cream (labels, pages, steam)
  m: "#c9cde0", // light metal
  M: "#8b8fa8", // dark metal
  k: "#4a3a6b", // dark detail (buttons, pads)
  l: "#5cb8ff", // screen / lens
  L: "#a8e0ff", // screen shine
  y: "#ffd84a", // lamp glow / flame
  Y: "#fff0a0", // flame center
  p: "#ff86a8", // pink (eraser, power button)
  c: "#6b4a3a", // coffee
  r: "#e0905a", // terracotta pot
  R: "#a8573a", // terracotta pot shade
};

export type SpriteTemplate = {
  /** Unique name, handy for debugging. */
  id: string;
  /** Words matched (whole word, plurals ok) against the detection label. */
  keywords: readonly string[];
  /** The pixel grid, top to bottom. Every row must be the same width. */
  rows: readonly string[];
  /** Extra or overriding fixed colors for this template only. */
  colors?: Readonly<Record<string, string>>;
};

